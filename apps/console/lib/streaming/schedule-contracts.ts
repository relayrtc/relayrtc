import { z } from "zod";
export const scheduledBroadcastSchema = z.object({
  id: z.string(),
  streamId: z.string(),
  broadcastId: z.string(),
  operationId: z.string(),
  organizationId: z.string(),
  projectId: z.string(),
  environmentId: z.string(),
  name: z.string(),
  state: z.enum([
    "scheduled",
    "starting",
    "running",
    "ending",
    "completed",
    "missed",
    "failed",
    "cancelled",
  ]),
  version: z.number(),
  lastError: z.string().nullable(),
  startsAt: z.string(),
  endsAt: z.string(),
  timeZone: z.string(),
  sourceWaitSeconds: z.number(),
  catchUpSeconds: z.number(),
  publisherEarlySeconds: z.number(),
  viewerEarlySeconds: z.number(),
  viewerAfterSeconds: z.number(),
  notifyBeforeSeconds: z.number().nullable(),
  publisherOpensAt: z.string(),
  viewerOpensAt: z.string(),
  viewerClosesAt: z.string(),
  readinessDeadline: z.string(),
  createdAt: z.string(),
  updatedAt: z.string(),
  startedAt: z.string().nullable(),
  endedAt: z.string().nullable(),
});
export const schedulePageSchema = z.object({
  data: z.array(scheduledBroadcastSchema),
  nextCursor: z.string().nullable(),
  limits: z.object({ activeSchedules: z.number(), maxActiveSchedules: z.number() }),
});
export const scheduledPlaybackSchema = z.object({
  scheduleId: z.string(),
  streamId: z.string(),
  broadcastId: z.string(),
  state: z.enum(["ready", "starting", "live", "ended", "failed"]),
  scheduleState: scheduledBroadcastSchema.shape.state,
  sourceSessionId: z.string().nullable(),
  generation: z.number().nullable(),
  startsAt: z.string(),
  endsAt: z.string(),
  serverTime: z.string(),
  countdownSeconds: z.number(),
  publisherOpensAt: z.string(),
  viewerOpensAt: z.string(),
  viewerClosesAt: z.string(),
});
export type ConsoleSchedule = z.infer<typeof scheduledBroadcastSchema>;
